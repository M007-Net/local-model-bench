// Independent mathematical invariants catch reference mistakes rather than merely
// asking the same checker to accept keys generated by itself.
test('IPv4 and VLSM keys satisfy address arithmetic, capacity, alignment and containment',()=>{
 const n=(ip:string)=>ip.split('.').reduce((a,b)=>a*256+Number(b),0);
 for(const t of pack.tests.filter(t=>t.category==='IPv4 subnetting')){
  const k=JSON.parse(t.answerKey),[network,prefix]=k.network.split('/'),size=2**(32-Number(prefix));
  const host=t.prompt.match(/Host ([\d.]+)\/(\d+)/)!;
  assert.ok(n(host[1])>=n(network)&&n(host[1])<n(network)+size);
  assert.equal(n(network)%size,0);assert.equal(n(k.broadcast)-n(network)+1,size);
  assert.equal(n(k.first),n(network)+1);assert.equal(n(k.last),n(k.broadcast)-1);assert.equal(k.hosts,size-2);
 }
 for(const t of pack.tests.filter(t=>t.category==='VLSM planning')){
  const k=JSON.parse(t.answerKey),base=n(t.prompt.match(/inside ([\d.]+)\/24/)![1]);
  const demands=t.prompt.match(/respectively ([\d, ]+) usable/)![1].split(',').map(Number);
  let last=base,reserved=0;
  k.cidrs.forEach((cidr:string,j:number)=>{const [ip,p]=cidr.split('/'),size=2**(32-Number(p));
   assert.equal(n(ip)%size,0);assert.equal(n(ip),last);assert.ok(size-2>=demands[j]);assert.ok(size/2-2<demands[j]);
   assert.ok(n(ip)+size<=base+256);last=n(ip)+size;reserved+=size;
  });assert.equal(k.reserved,reserved);assert.equal(k.free,256-reserved);
 }
});
test('shortest paths independently agree with exhaustive simple-path enumeration',()=>{
 for(const t of pack.tests.filter(t=>t.category==='Link-state paths')){
  const p=t.prompt,k=JSON.parse(t.answerKey),ab=Number(p.match(/A-B cost (\d+)/)![1]),bd=Number(p.match(/B-D cost (\d+)/)![1]),ac=Number(p.match(/A-C cost (\d+)/)![1]),cd=Number(p.match(/C-D cost (\d+)/)![1]);
  for(const after of [false,true]){
   const edges=[['A','B',ab],['B','D',bd],['C','D',cd],['B','C',50],...(!after||p.includes('A-C is up')?[['A','C',ac]]:[])];
   const results:{path:string[];cost:number}[]=[];
   const visit=(path:string[],cost:number)=>{const at=path.at(-1)!;if(at==='D'){results.push({path,cost});return;}for(const [a,b,w] of edges){const next=at===a?b:at===b?a:null;if(typeof next==='string'&&!path.includes(next))visit([...path,next],cost+Number(w));}};
   visit(['A'],0);results.sort((a,b)=>a.cost-b.cost||a.path.join('').localeCompare(b.path.join('')));
   assert.deepEqual(k[after?'after':'before'],results[0].path);assert.equal(k[after?'after_cost':'before_cost'],results[0].cost);
  }
 }
});
