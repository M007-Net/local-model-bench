import {_electron as electron} from 'playwright';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const dir=path.resolve('work/accounting-mtp-ui');fs.mkdirSync(dir,{recursive:true});
const app=await electron.launch({executablePath:path.resolve('outputs/win-unpacked/Local Model Bench.exe'),args:[],env:{...process.env,LMB_DATA_DIR:path.join(dir,'data')},timeout:60000});
const page=await app.firstWindow();page.setDefaultTimeout(20000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.getByRole('heading',{name:'Choose models to benchmark'}).waitFor();
 const snapshot=await page.evaluate(()=>window.bench.snapshot());
 assert.equal(snapshot.tests.filter(t=>t.category==='Accounting').length,12);
 const models=await page.evaluate(()=>window.bench.models());
 const supported=models.filter(m=>m.nativeMtp?.supported===true);assert.ok(supported.length>0);
 await page.getByLabel('Native MTP support',{exact:true}).selectOption('yes');
 assert.equal(await page.locator('.model-card').count(),supported.length);
 await page.getByRole('button',{name:'Select shown',exact:true}).click();
 await page.getByRole('button',{name:'Configure benchmark'}).click();
 assert.equal(await page.getByLabel('Enable native MTP',{exact:true}).isChecked(),false);
 await page.getByLabel('Enable native MTP',{exact:true}).check();
 assert.equal(await page.getByLabel('MTP draft tokens',{exact:true}).inputValue(),'2');
 await page.getByRole('button',{name:'Select native MTP models',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Start benchmark',exact:true}).isEnabled(),true);
 const unsupported=models.find(m=>m.nativeMtp?.supported===false);
 await page.locator('.selection-list label').filter({hasText:unsupported.display_name}).first().locator('input').check();
 assert.equal(await page.getByRole('button',{name:'Start benchmark',exact:true}).isEnabled(),false);
 await page.getByLabel('Enable native MTP',{exact:true}).uncheck();
 assert.equal(await page.getByRole('button',{name:'Start benchmark',exact:true}).isEnabled(),true);
 await page.getByLabel('Enable native MTP',{exact:true}).check();
 await page.getByRole('button',{name:'Select native MTP models',exact:true}).click();
 await page.getByRole('button',{name:'Use accounting suite',exact:true}).click();
 assert.equal(await page.locator('.selection-list').nth(1).locator('input:checked').count(),12);
 await page.screenshot({path:path.join(dir,'mtp-run.png'),fullPage:true});
 await page.getByRole('button',{name:'Tests',exact:true}).click();
 const card=page.locator('.test-card').filter({hasText:'Owner investment and cash expense'});
 await card.getByRole('button',{name:'Edit test'}).click();
 assert.equal(await page.getByLabel('Check type',{exact:true}).inputValue(),'json-equal');
 await page.screenshot({path:path.join(dir,'accounting-editor.png')});
 await page.getByRole('button',{name:'Save test',exact:true}).click();
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(dir,'result.json'),JSON.stringify({passed:true,accountingCases:12,supportedMtpModels:supported.length,errors},null,2));
 console.log('Accounting library/editor and MTP filter/toggle/compatibility gating passed.');
}finally{await app.close();}
